// Copi 菜单里"Copi Clipboard (Safe)"下面那一行：Empty、Hidden（有文字）、Concealed（机密）。读不到时只作参考
func copiClipboardState() -> String {
    var state = "打不开 Copi 的菜单"
    copiPanel { app in
        guard let header = findInCopiPanel(app, { element in
            [axString(element, kAXValueAttribute), axString(element, kAXTitleAttribute), axString(element, kAXDescriptionAttribute)]
                .contains { $0?.localizedCaseInsensitiveContains("Copi Clipboard") == true }
        }),
              let headerFrame = frame(header) else {
            state = "面板里找不到 Copi Clipboard 那一节"
            return
        }
        let values = ["Empty", "Hidden", "•••••••• (Concealed)"]
        let below = findAll(app, maxDepth: 40, limit: 30000) { element in
            role(element) == kAXStaticTextRole && values.contains(axString(element, kAXValueAttribute) ?? "")
        }.compactMap { element -> (String, CGFloat)? in
            guard let elementFrame = frame(element), elementFrame.minY > headerFrame.minY else {
                return nil
            }
            return (axString(element, kAXValueAttribute) ?? "", elementFrame.minY - headerFrame.minY)
        }.min { $0.1 < $1.1 }
        state = below.map { $0.0 == "•••••••• (Concealed)" ? "Concealed" : $0.0 } ?? "找不到那一行"
    }
    return state
}

// MARK: - 临时改 Copi 的设置

// 临时把 Copi 的一个开关设成 value，做完 body 改回去（原来没设过就删掉）。Copi 会提示"设置被别的程序改了"，最后统一点掉
func withCopiBool(_ key: String, _ value: Bool, _ body: () throws -> Void) rethrows {
    let original = copiDefault(key)
    _ = run("/usr/bin/defaults", ["write", "com.gokoding.Copi", key, "-bool", value ? "true" : "false"])
    sleepMS(1500)
    defer {
        if let original {
            _ = run("/usr/bin/defaults", ["write", "com.gokoding.Copi", key, "-bool", original == "1" ? "true" : "false"])
        } else {
            _ = run("/usr/bin/defaults", ["delete", "com.gokoding.Copi", key])
        }
        sleepMS(1500)
    }
    try body()
}

// 临时把一个 App 加进 Apps Using the Normal Clipboard。读不懂原来的设置时不改，返回 false
func withNormalClipboardApp(_ bundleID: String, _ body: () throws -> Void) rethrows -> Bool {
    let key = "normalClipboardApps"
    let raw = copiDefault(key)
    let original = UserDefaults(suiteName: "com.gokoding.Copi")?.stringArray(forKey: key)
    guard raw == nil || original != nil else {
        return false
    }
    _ = run("/usr/bin/defaults", ["write", "com.gokoding.Copi", key, "-array"] + (original ?? []) + [bundleID])
    sleepMS(1500)
    defer {
        if let original {
            _ = run("/usr/bin/defaults", ["write", "com.gokoding.Copi", key, "-array"] + original)
        } else {
            _ = run("/usr/bin/defaults", ["delete", "com.gokoding.Copi", key])
        }
        sleepMS(1500)
    }
    try body()
    return true
}

// 一项测试：中止（焦点不对之类）只记这一项，接着跑下一项（每次发按键前仍然过 gate）
func matrixCase(_ id: String, _ name: String, _ body: () throws -> Void) {
    do {
        try body()
    } catch let error as Abort {
        record(id, name, "ABORT", error.reason)
    } catch {
        record(id, name, "ABORT", "\(error)")
    }
}

