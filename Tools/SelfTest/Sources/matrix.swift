// 往 Copi 里放哨兵（在源文档里 ⌘A ⌘C）。act：之后按一下 → 键——Copi 不收"安全复制之后 3 秒内、用户没有操作时"别的程序写进来的
// 内容（防剪贴板劫持，见 M.15），按过键就不算。再等 0.7 秒，让组合键之后的加密检查过去，下面量到的是平时（每 20 ms 一次）的检查
func loadSentinel(_ docs: MatrixDocs, act: Bool = true) throws {
    bringToFront(docs.source)
    try gate(docs.source)
    chord(keyA(), cmd)
    try gate(docs.source)
    chord(keyC(), cmd)
    sleepMS(150)
    if act {
        try gate(docs.source)
        chord(CGKeyCode(kVK_RightArrow))
        sleepMS(700)
    }
}

// 清空目标文档，⌘V，读出粘贴进来的文字。Copi 是空的时候 ⌘V 原样交给 TextEdit，粘贴的是系统剪贴板上的东西
// （纯文本文档里放不进图片：只有图片时粘贴为空）
func probeCopi(_ docs: MatrixDocs) throws -> String? {
    bringToFront(docs.probe)
    try gate(docs.probe)
    chord(keyA(), cmd)
    chord(CGKeyCode(kVK_Delete))
    sleepMS(150)
    try gate(docs.probe)
    chord(keyV(), cmd)
    sleepMS(900)
    return textValue(docs.probe)
}

func shortDescription(_ value: String?) -> String {
    guard let value else {
        return "读不到"
    }
    if value.isEmpty {
        return "空"
    }
    if value == sentinelText {
        return "复制之前放进 Copi 的哨兵"
    }
    return value.utf16.count > 60 ? "\(value.utf16.count) 字符" : "「\(value)」"
}

