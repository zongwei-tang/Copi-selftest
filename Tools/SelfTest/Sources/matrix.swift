func utf8(_ text: String) -> Data {
    Data(text.utf8)
}

func rtfData(_ text: String) -> Data {
    let string = NSAttributedString(string: text)
    return string.rtf(from: NSRange(location: 0, length: string.length), documentAttributes: [:]) ?? Data()
}

// 清空系统剪贴板、写进一个 item：entries 里的类型带数据，lazy 里的类型只声明、不提供数据
func writeGeneral(_ entries: [(NSPasteboard.PasteboardType, Data)], lazy: [NSPasteboard.PasteboardType] = []) {
    let pasteboard = NSPasteboard.general
    pasteboard.clearContents()
    let item = NSPasteboardItem()
    for (type, data) in entries {
        item.setData(data, forType: type)
    }
    if !lazy.isEmpty {
        item.setDataProvider(neverProvider, forTypes: lazy)
    }
    pasteboard.writeObjects([item])
}

// 剪贴板上有没有这几种类型里的任何一种（只看类型）
func hasAny(_ pasteboard: NSPasteboard, _ types: Set<String>) -> Bool {
    !Set((pasteboard.types ?? []).map(\.rawValue)).isDisjoint(with: types)
}

// 写进去的东西在剪贴板上停了多久：第一次、最后一次看到的时刻（从 start 起的毫秒）
struct Presence {
    var first: Int?
    var last: Int?

    var ms: Int {
        first.map { (last ?? $0) - $0 + 1 } ?? 0
    }

    func summary(_ what: String) -> String {
        first.map { "\(what)在剪贴板上约 \(ms) ms（\($0)–\(last ?? $0) ms）" } ?? "\(what)没有出现在剪贴板上"
    }
}

// 从 start 起到 untilMS 毫秒，每 1 毫秒看一次
func sample(_ pasteboard: NSPasteboard, _ types: Set<String>, from start: Date, untilMS: Int, into presence: inout Presence) {
    while true {
        let elapsed = Int(Date().timeIntervalSince(start) * 1000)
        if elapsed >= untilMS {
            return
        }
        if hasAny(pasteboard, types) {
            presence.first = presence.first ?? elapsed
            presence.last = elapsed
        }
        usleep(1000)
    }
}

// 后台每 1 毫秒看一次剪贴板的类型（按键、点菜单的同时也在看）：matches 成立的第一次、最后一次（从创建时起的毫秒），以及那时看到的类型
final class TypeWatcher {
    private let lock = NSLock()
    private let finished = DispatchSemaphore(value: 0)
    private var running = true
    private var presence = Presence()
    private var seen: Set<String> = []
    private let start = Date()

    init(_ pasteboard: NSPasteboard, _ matches: @escaping (Set<String>) -> Bool) {
        Thread { [self] in
            while isRunning {
                let types = Set((pasteboard.types ?? []).map(\.rawValue))
                if matches(types) {
                    let ms = Int(Date().timeIntervalSince(start) * 1000)
                    lock.lock()
                    presence.first = presence.first ?? ms
                    presence.last = ms
                    seen.formUnion(types)
                    lock.unlock()
                }
                usleep(1000)
            }
            finished.signal()
        }.start()
    }

    private var isRunning: Bool {
        lock.lock()
        defer { lock.unlock() }
        return running
    }

    // 等取样的线程真正停下来，返回结果
    func stop() -> (presence: Presence, types: Set<String>) {
        lock.lock()
        let wasRunning = running
        running = false
        lock.unlock()
        if wasRunning {
            finished.wait()
        }
        lock.lock()
        defer { lock.unlock() }
        return (presence, seen)
    }
}

// 文字被挪走得多快：PASS 50 ms 以内（Copi 平时每 20 ms 看一次），CHECK 150 ms 以内（虚拟机上计时不准），再长或者一直在都是 FAIL
func moveStatus(_ presence: Presence, stillThere: Bool) -> String {
    stillThere || presence.ms > 150 ? "FAIL" : (presence.ms <= 50 ? "PASS" : "CHECK")
}

