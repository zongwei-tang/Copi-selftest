                   "第一次：\(firstPresence.summary("文字"))，之后 ⌘V 粘贴出\(shortDescription(firstGot))；第二次：\(presence.summary("文字"))；最后还在=\(stillThere)；之后 ⌘V 粘贴出\(same ? "这段文字" : shortDescription(got))")
        }
    }

    // 访达里的文件：⌘C 放行（文件留在系统剪贴板上，带着文件名文字）；⌥⌘C 拷贝路径是访达自己写的文字，Copi 挪走
    matrixCase("K.11", "访达里复制文件") {
        let file = writeFixture("k11-file.txt", "k11")
        _ = run("/usr/bin/open", ["-R", file.path])
        guard var finder = waitWindow("com.apple.finder", "Finder", titleContains: "fixtures", timeout: 10) else {
            record("K.11", "访达里复制文件", "SKIP", "访达没有打开测试文件夹")
            return
        }
        finder.titleCheck = { $0.contains("fixtures") }
        bringToFront(finder)
        sleepMS(800)
        let diag = focusedClassDiag(finder.pid)
        let fileTypes: Set<String> = [NSPasteboard.PasteboardType.fileURL.rawValue]
        try loadSentinel(docs)
        bringToFront(finder)
        try gate(finder)
        let start = Date()
        chord(keyC(), cmd)
        var files = Presence()
        sample(.general, fileTypes, from: start, untilMS: 1200, into: &files)
        let fileStays = hasAny(.general, fileTypes)
        let nameStays = hasAny(.general, plain)
        // 在访达里 ⌘V：Copi 把文件短暂放回剪贴板，访达复制出"k11-file copy.txt"
        let copyURL = fixtures.appendingPathComponent("k11-file copy.txt")
        try? FileManager.default.removeItem(at: copyURL)
        bringToFront(finder)
        try gate(finder)
        chord(keyV(), cmd)
        var pastedFile = false
        for _ in 0..<25 where !pastedFile {
            sleepMS(200)
            pastedFile = FileManager.default.fileExists(atPath: copyURL.path)
        }
        sleepMS(2000)
        let leftAfterPaste = hasAny(.general, fileTypes)
        let quick = files.ms > 0 && files.ms <= 1100
        record("K.11", "访达里选中文件 ⌘C：放行，约半秒后文件取下、存进 Copi；在访达里 ⌘V 复制出这个文件，之后不留在剪贴板上",
               !fileStays && quick && pastedFile && !leftAfterPaste ? "PASS" : "FAIL",
               "按 ⌘C 前：\(diag)；\(files.summary("文件"))；1.2 秒后文件还在=\(fileStays)、文件名文字还在=\(nameStays)；访达里 ⌘V 复制出了文件=\(pastedFile)；粘贴 2 秒后还在=\(leftAfterPaste)")
        // 删掉复制出来的文件，重新选中原来的那个（⌥⌘C 拷贝的是选中文件的路径）
        try? FileManager.default.removeItem(at: copyURL)
        _ = run("/usr/bin/open", ["-R", file.path])
        sleepMS(1000)
        // ⌥⌘C：拷贝路径
        bringToFront(finder)
        sleepMS(700)
        try gate(finder)
        let watcher = TypeWatcher(.general) { !$0.isDisjoint(with: plain) }
        chord(keyC(), [CGKeyCode(kVK_Command): .maskCommand, CGKeyCode(kVK_Option): .maskAlternate])
        sleepMS(800)
        let presence = watcher.stop().presence
        let stillThere = hasAny(.general, plain)
        let got = try probeCopi(docs)
        let status = got == file.path ? moveStatus(presence, stillThere: stillThere) : "FAIL"
        record("K.12", "访达 ⌥⌘C 拷贝路径：访达自己写进文字，Copi 挪走", status,
               "\(presence.summary("文字"))；最后还在=\(stillThere)；之后 ⌘V 粘贴出\(got == file.path ? "这个文件的路径" : shortDescription(got))")
        bringToFront(finder)
        if (try? gate(finder)) != nil {
            chord(keyW(), cmd)
        }
    }

    // 访达里 ⌘C 文件之后 ⌥⌘V（"移动到这里"）：Copi 把收走的文件短暂放回剪贴板，访达把文件移过来
    matrixCase("K.11m", "访达里 ⌥⌘V 移动文件") {
        let file = writeFixture("k11m-file.txt", "k11m")
        let folder = fixtures.appendingPathComponent("k11-move")
        try? FileManager.default.removeItem(at: folder)
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        let placeholder = folder.appendingPathComponent("placeholder.txt")
        try? "k11m".write(to: placeholder, atomically: true, encoding: .utf8)
        let moved = folder.appendingPathComponent("k11m-file.txt")
        _ = run("/usr/bin/open", ["-R", file.path])
        guard var source = waitWindow("com.apple.finder", "Finder", titleContains: "fixtures", timeout: 10) else {
            record("K.11m", "访达里 ⌥⌘V 移动文件", "SKIP", "访达没有打开测试文件夹")
            return
        }
        source.titleCheck = { $0.contains("fixtures") }
        bringToFront(source)
        sleepMS(800)
        try gate(source)
        chord(keyC(), cmd)
        // 等 Copi 把文件从剪贴板上取下来（约半秒）
        sleepMS(1500)
        let fileTypes: Set<String> = [NSPasteboard.PasteboardType.fileURL.rawValue]
        let takenOff = !hasAny(.general, fileTypes)
        _ = run("/usr/bin/open", ["-R", placeholder.path])
        guard var destination = waitWindow("com.apple.finder", "Finder", titleContains: "k11-move", timeout: 10) else {
            record("K.11m", "访达里 ⌥⌘V 移动文件", "SKIP", "访达没有打开目标文件夹")
            return
        }
        destination.titleCheck = { $0.contains("k11-move") }
        bringToFront(destination)
        sleepMS(800)
        try gate(destination)
        chord(keyV(), [CGKeyCode(kVK_Command): .maskCommand, CGKeyCode(kVK_Option): .maskAlternate])
        var done = false
        for _ in 0..<25 where !done {
            sleepMS(200)
            done = FileManager.default.fileExists(atPath: moved.path) && !FileManager.default.fileExists(atPath: file.path)
        }
        sleepMS(2000)
        let left = hasAny(.general, fileTypes)
        record("K.11m", "访达里 ⌘C 文件之后在另一个文件夹 ⌥⌘V（移动到这里）：文件移过来，之后不留在剪贴板上",
               takenOff && done && !left ? "PASS" : "FAIL",
               "⌘C 1.5 秒后文件已从剪贴板上取下=\(takenOff)；⌥⌘V 后文件移到了目标文件夹=\(done)；2 秒后剪贴板上还有文件=\(left)")
        bringToFront(destination)
        if (try? gate(destination)) != nil {
            chord(keyW(), cmd)
        }
    }

    // 图片：拿着焦点的是图片本身时 ⌘C 放行（README 第 45 行）
    matrixCase("K.16", "预览里复制图片") {
        let url = fixtures.appendingPathComponent("k16-dot.png")
        try? tinyPNG.write(to: url)
        openWith("Preview", url.path)
        guard var viewer = waitWindow("com.apple.Preview", "Preview", titleContains: "k16-dot", timeout: 15) else {
            record("K.16", "预览里复制图片", "SKIP", "预览没有打开测试图片")
            return
        }
        viewer.titleCheck = { $0.contains("k16-dot") }
        bringToFront(viewer)
        sleepMS(800)
        let diag = focusedClassDiag(viewer.pid)
        let imageTypes: Set<String> = [NSPasteboard.PasteboardType.png.rawValue, NSPasteboard.PasteboardType.tiff.rawValue]
        try loadSentinel(docs)
        bringToFront(viewer)
        try gate(viewer)
        let start = Date()
        chord(keyC(), cmd)
        var images = Presence()
        sample(.general, imageTypes, from: start, untilMS: 1500, into: &images)
        let stays = hasAny(.general, imageTypes)
        // 放行了的话预览自己复制（图片在剪贴板上出现过），约半秒后 Copi 取下来；粘贴进富文本文档里应是这张图
        let copied = images.first != nil
        let rich = try openTextEdit("dst-matrix-k16.rtf", emptyRTF)
        openedWindows.append(rich)
        let pasted = try probeRich(rich)
        let ok = copied && !stays && images.ms <= 1100 && attachmentCount(pasted) == 1
        record("K.16", "预览里 ⌘C（整张图片）：放行，约半秒后图片取下、存进 Copi；粘贴出这张图", ok ? "PASS" : "FAIL",
               "按 ⌘C 前：\(diag)；\(images.summary("图片"))；1.5 秒后图片还在=\(stays)；粘贴进富文本文档后附件 \(attachmentCount(pasted)) 个"
               + (copied ? "" : "（没有放行：预览里拿着焦点的不是图片本身，角色见上）"))
        bringToFront(viewer)
        if (try? gate(viewer)) != nil {
            chord(keyW(), cmd)
        }
        NSPasteboard.general.clearContents()
    }
