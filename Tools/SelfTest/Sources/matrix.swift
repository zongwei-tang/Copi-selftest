// 焦点元素的角色和 class（网页里认代码编辑器、终端靠 class）
func focusedClassDiag(_ pid: pid_t) -> String {
    guard let element = focusedElement(pid) else {
        return "焦点元素=nil"
    }
    let classes = (ax(element, "AXDOMClassList") as? [String]) ?? []
    return "焦点角色=\(role(element) ?? "nil") class=\(classes.isEmpty ? "无" : classes.joined(separator: " "))"
}

// 菜单栏里带这个快捷键（⌘ + commandChar，不带别的修饰键）的菜单项（不打开菜单）
func menuItem(_ pid: pid_t, commandChar: String) -> AXUIElement? {
    guard let menuBar = axElement(ax(AXUIElementCreateApplication(pid), kAXMenuBarAttribute)) else {
        return nil
    }
    for barItem in axChildren(menuBar) {
        guard let menu = axChildren(barItem).first else {
            continue
        }
        if let item = axChildren(menu).first(where: {
            axString($0, kAXMenuItemCmdCharAttribute) == commandChar && (ax($0, kAXMenuItemCmdModifiersAttribute) as? NSNumber)?.intValue == 0
        }) {
            return item
        }
    }
    return nil
}

