// Copi 在屏幕下方显示的小窗口（宽 420 点，进度、确认提醒）现在显示着
func copiHUDVisible() -> Bool {
    guard let windows = CGWindowListCopyWindowInfo([.optionOnScreenOnly], kCGNullWindowID) as? [[String: Any]] else {
        return false
    }
    return windows.contains { window in
        guard (window[kCGWindowOwnerName as String] as? String) == "Copi",
              let bounds = window[kCGWindowBounds as String] as? [String: Any], let width = bounds["Width"] as? Double else {
            return false
        }
        return Int(width.rounded()) == 420
    }
}

